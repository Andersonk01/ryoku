function fold(text) {
    var s = String(text === undefined || text === null ? "" : text);
    if (s.normalize)
        s = s.normalize("NFD").replace(/[̀-ͯ]/g, "");
    return s.toUpperCase();
}

function glyph(ch) {
    return glyphs[ch] || glyphs[" "];
}

// Every cell of every glyph, flattened, so a Repeater can draw them:
// { gi: glyph index, col: absolute column, row, on: lit in the final art }
function cells(text) {
    var s = fold(text);
    var out = [];
    for (var gi = 0; gi < s.length; gi++) {
        var g = glyph(s[gi]);
        for (var row = 0; row < H; row++)
            for (var c = 0; c < W; c++)
                out.push({ gi: gi, col: gi * (W + 1) + c, row: row, on: g[row][c] === "1" });
    }
    return out;
}

function columns(text) {
    var n = fold(text).length;
    return n <= 0 ? 0 : n * (W + 1) - 1;
}
